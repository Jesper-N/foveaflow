import { PatternSampler } from "../engine/pattern-sampler";
import { createRng } from "../engine/random";
import type { PatternId, TargetFrame } from "../engine/types";
import { pursuitPatterns } from "../settings/patterns";

type Point = [x: number, y: number];

const ARENA = { height: 240, width: 320 };

const SCALE = 0.1;

const STEP_PX = 4;

const SEED = 7;

const TOLERANCE = 0.12;

const CLOSE_DISTANCE = 0.3;

const MIN_LOOP_PX = 300;

const SAME_HEADING_COSINE = 0.95;

const openTravelPx: Partial<Record<PatternId, number>> = {
  bounce: 1500,
  diagonal: 1900,
  directionChange: 1500,
  downLeftSweep: 900,
  downRightSweep: 900,
  horizontalSweep: 560,
  randomWalk: 1400,
  verticalSweep: 420,
};

const MAX_TRAVEL_PX = 6000;

const drawnGlyphs: Partial<Record<PatternId, string>> = {
  directionChange: "M5 17L10.5 7L15.5 16L21 6.5L27 14",
  randomWalk: "M5 16C7 9 11 6.5 13.5 9.5S15 17 19 17 23.5 9 27 8",
};

const distanceToSegment = ([x, y]: Point, [ax, ay]: Point, [bx, by]: Point) => {
  const dx = bx - ax;
  const dy = by - ay;
  const lengthSquared = dx * dx + dy * dy;

  const t =
    lengthSquared === 0
      ? 0
      : Math.max(
          0,
          Math.min(1, ((x - ax) * dx + (y - ay) * dy) / lengthSquared)
        );

  return Math.hypot(x - (ax + t * dx), y - (ay + t * dy));
};

const simplify = (points: Point[]): Point[] => {
  const [first] = points;
  const last = points.at(-1);

  if (!first || !last || points.length < 3) {
    return points;
  }

  let farthest = 0;
  let farthestIndex = 0;

  for (let index = 1; index < points.length - 1; index += 1) {
    const point = points[index];

    if (point) {
      const distance = distanceToSegment(point, first, last);

      if (distance > farthest) {
        farthest = distance;
        farthestIndex = index;
      }
    }
  }

  if (farthest <= TOLERANCE) {
    return [first, last];
  }

  return [
    ...simplify(points.slice(0, farthestIndex + 1)).slice(0, -1),
    ...simplify(points.slice(farthestIndex)),
  ];
};

const isSameHeading = (a: Point, b: Point, c: Point, d: Point) => {
  const ux = b[0] - a[0];
  const uy = b[1] - a[1];
  const vx = d[0] - c[0];
  const vy = d[1] - c[1];
  const lengths = Math.hypot(ux, uy) * Math.hypot(vx, vy);

  return lengths > 0 && (ux * vx + uy * vy) / lengths > SAME_HEADING_COSINE;
};

const format = (value: number) => String(Math.round(value * 10) / 10);

export const buildPatternGlyph = (id: PatternId) => {
  const drawn = drawnGlyphs[id];

  if (drawn !== undefined) {
    return drawn;
  }

  const sampler = new PatternSampler();
  const rng = createRng(SEED);
  const frames: TargetFrame[] = [];
  const openTravel = openTravelPx[id];
  const points: Point[] = [];

  for (
    let travelPx = 0;
    travelPx <= (openTravel ?? MAX_TRAVEL_PX);
    travelPx += STEP_PX
  ) {
    sampler.sample(
      frames,
      id,
      ARENA,
      {
        distractorCount: 0,
        pathMarginPx: 30,
        radiusPx: 1,
        targetCount: 1,
        travelPx,
      },
      rng
    );
    const [frame] = frames;

    if (frame) {
      const point: Point = [frame.x * SCALE, frame.y * SCALE];
      points.push(point);
      const [start, second] = points;
      const previous = points.at(-2);

      if (
        openTravel === undefined &&
        start &&
        second &&
        previous &&
        travelPx > MIN_LOOP_PX &&
        Math.hypot(point[0] - start[0], point[1] - start[1]) < CLOSE_DISTANCE &&
        isSameHeading(previous, point, start, second)
      ) {
        points.push(start);
        break;
      }
    }
  }

  return `M${simplify(points)
    .map(([x, y]) => `${format(x)} ${format(y)}`)
    .join("L")}`;
};

export const renderPatternGlyphModule = () => {
  const entries = pursuitPatterns
    .map(({ id }) => `  ${id}:\n    "${buildPatternGlyph(id)}",`)
    .join("\n");

  return `// Generated by scripts/generate-pattern-glyphs.ts. Do not edit.
import type { PursuitPatternId } from "../settings/patterns";

export const patternGlyphs: Record<PursuitPatternId, string> = {
${entries}
};
`;
};
